-- POS: create a staff-initiated order (auto-confirmed, no QR verification)
-- ---------------------------------------------------------------------------
create or replace function public.create_pos_order(p_session_token text, p_order jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  session_row record;
  new_order_id bigint;
  requested_count integer := 0;
  matched_count integer := 0;
  computed_total numeric(10,2) := 0;
  p_items jsonb := coalesce(p_order -> 'items', '[]'::jsonb);
  p_table_id bigint := nullif((p_order ->> 'tableId'), '')::bigint;
  p_customer_name text := nullif(trim(coalesce(p_order ->> 'customerName','')), '');
  p_table_number text := nullif(trim(coalesce(p_order ->> 'tableNumber','')), '');
  p_special_request text := nullif(trim(coalesce(p_order ->> 'specialRequest','')), '');
  resolved_table_number text := p_table_number;
  dummy_code varchar(6);
begin
  select s.admin_id, s.restaurant_id, s.email, s.role
  into session_row
  from public._require_admin_session(p_session_token) s;

  if p_table_id is not null then
    select table_number into resolved_table_number
    from public.tables
    where id = p_table_id and restaurant_id = session_row.restaurant_id;
  end if;

  select count(*) into requested_count from jsonb_array_elements(p_items);
  if requested_count = 0 then
    raise exception 'Add at least one item before charging.';
  end if;

  with ri as (
    select (item->>'menuItemId')::bigint as menu_item_id,
           greatest(1, coalesce((item->>'quantity')::integer,0)) as quantity
    from jsonb_array_elements(p_items) item
  )
  select count(*), coalesce(sum(mi.price * ri.quantity), 0)
  into matched_count, computed_total
  from ri
  join public.menu_items mi on mi.id = ri.menu_item_id
    and mi.restaurant_id = session_row.restaurant_id
    and mi.is_available = true;

  if matched_count <> requested_count then
    raise exception 'One or more selected items are not available.';
  end if;

  insert into public.orders (
    restaurant_id, table_id, customer_name, table_number,
    special_request, status, total_price, is_verified, confirmed_at
  )
  values (
    session_row.restaurant_id, p_table_id, p_customer_name,
    resolved_table_number, p_special_request,
    'confirmed', computed_total, true, now()
  )
  returning id into new_order_id;

  with ri as (
    select (item->>'menuItemId')::bigint as menu_item_id,
           greatest(1, coalesce((item->>'quantity')::integer,0)) as quantity
    from jsonb_array_elements(p_items) item
  )
  insert into public.order_items (order_id, menu_item_id, quantity, price_at_time)
  select new_order_id, mi.id, ri.quantity, mi.price
  from ri
  join public.menu_items mi on mi.id = ri.menu_item_id
    and mi.restaurant_id = session_row.restaurant_id
    and mi.is_available = true;

  -- POS orders don't need a verification code but the FK requires one.
  loop
    dummy_code := lpad((floor(random() * 900000) + 100000)::int::text, 6, '0');
    exit when not exists (select 1 from public.order_verifications where code = dummy_code);
  end loop;
  insert into public.order_verifications (order_id, code, expires_at, verified_at)
  values (new_order_id, dummy_code, now() + interval '1 second', now());

  -- Mark table as occupied
  if p_table_id is not null then
    update public.tables set status = 'occupied'
    where id = p_table_id and restaurant_id = session_row.restaurant_id;
  end if;

  return jsonb_build_object(
    'orderId', new_order_id,
    'status', 'confirmed',
    'totalPrice', computed_total
  );
end;
$$;

