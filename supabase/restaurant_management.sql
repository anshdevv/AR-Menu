-- ---------------------------------------------------------------------------
-- Staff: verify a customer's order code -> moves order to 'confirmed'
-- ---------------------------------------------------------------------------
create or replace function public.verify_order_code(p_session_token text, p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  session_row record;
  normalized_code text := trim(coalesce(p_code, ''));
  matched_order record;
begin
  perform public.expire_pending_orders();

  select s.admin_id, s.restaurant_id, s.email, s.role
  into session_row
  from public._require_admin_session(p_session_token) s;

  select o.id, o.status, ov.expires_at, ov.verified_at
  into matched_order
  from public.orders o
  join public.order_verifications ov on ov.order_id = o.id
  where o.restaurant_id = session_row.restaurant_id
    and ov.code = normalized_code;

  if matched_order is null then
    raise exception 'Code not found for this restaurant.';
  end if;

  if matched_order.verified_at is not null or matched_order.status <> 'pending_verification' then
    raise exception 'This order is already verified.';
  end if;

  if matched_order.expires_at <= now() then
    update public.orders set status = 'expired', is_verified = false where id = matched_order.id;
    raise exception 'This verification code has expired.';
  end if;

  update public.order_verifications set verified_at = now() where order_id = matched_order.id;
  update public.orders
  set status = 'confirmed', is_verified = true, confirmed_at = now()
  where id = matched_order.id;

  return jsonb_build_object('orderId', matched_order.id, 'status', 'confirmed', 'verifiedAt', now());
end;
$$;

-- ---------------------------------------------------------------------------
-- Staff: advance an order through the kitchen lifecycle
-- ---------------------------------------------------------------------------
create or replace function public.advance_order_status(
  p_session_token text,
  p_order_id bigint,
  p_status text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  session_row record;
  current_status text;
  next_status text := trim(coalesce(p_status, ''));
begin
  select s.admin_id, s.restaurant_id, s.email, s.role
  into session_row
  from public._require_admin_session(p_session_token) s;

  select status into current_status
  from public.orders
  where id = p_order_id and restaurant_id = session_row.restaurant_id;

  if current_status is null then
    raise exception 'Order not found for this restaurant.';
  end if;

  -- Allowed forward transitions.
  if not (
    (current_status = 'confirmed' and next_status = 'preparing') or
    (current_status = 'preparing' and next_status = 'ready') or
    (current_status = 'ready' and next_status = 'served')
  ) then
    raise exception 'Cannot move order from % to %.', current_status, next_status;
  end if;

  update public.orders
  set status = next_status,
      prep_started_at = case when next_status = 'preparing' then now() else prep_started_at end,
      ready_at = case when next_status = 'ready' then now() else ready_at end,
      served_at = case when next_status = 'served' then now() else served_at end
  where id = p_order_id;

  return jsonb_build_object('orderId', p_order_id, 'status', next_status);
end;
$$;

create or replace function public.cancel_order(p_session_token text, p_order_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  session_row record;
  current_status text;
begin
  select s.admin_id, s.restaurant_id, s.email, s.role
  into session_row
  from public._require_admin_session(p_session_token) s;

  select status into current_status
  from public.orders
  where id = p_order_id and restaurant_id = session_row.restaurant_id;

  if current_status is null then
    raise exception 'Order not found for this restaurant.';
  end if;

  if current_status in ('served', 'cancelled', 'expired') then
    raise exception 'Order cannot be cancelled from its current state.';
  end if;

  update public.orders set status = 'cancelled' where id = p_order_id;
  return jsonb_build_object('orderId', p_order_id, 'status', 'cancelled');
end;
$$;

