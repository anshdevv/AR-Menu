-- ---------------------------------------------------------------------------
-- Staff: expanded analytics with a date range
-- ---------------------------------------------------------------------------
create or replace function public.get_admin_analytics_v2(
  p_session_token text,
  p_from timestamptz default null,
  p_to timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  session_row record;
  range_from timestamptz := coalesce(p_from, now() - interval '30 days');
  range_to timestamptz := coalesce(p_to, now());
begin
  perform public.expire_pending_orders();

  select s.admin_id, s.restaurant_id, s.email, s.role
  into session_row
  from public._require_admin_session(p_session_token) s;

  return jsonb_build_object(
    'range', jsonb_build_object('from', range_from, 'to', range_to),
    'metrics', (
      select jsonb_build_object(
        'ordersToday', count(*) filter (where o.created_at >= date_trunc('day', now())),
        'revenueToday', coalesce(sum(o.total_price) filter (where o.created_at >= date_trunc('day', now()) and o.is_verified = true), 0),
        'pendingVerification', count(*) filter (where o.status = 'pending_verification'),
        'avgOrderValue', coalesce(avg(o.total_price) filter (where o.is_verified = true), 0),
        'verificationRate', case when count(*) = 0 then 0 else round((count(*) filter (where o.is_verified = true))::numeric / count(*)::numeric * 100, 1) end,
        'avgPrepMinutes', coalesce(round(avg(extract(epoch from (o.served_at - o.confirmed_at)) / 60) filter (where o.served_at is not null and o.confirmed_at is not null)::numeric, 1), 0),
        'tableTurnover', count(distinct o.table_id) filter (where o.created_at >= date_trunc('day', now()) and o.table_id is not null)
      )
      from public.orders o
      where o.restaurant_id = session_row.restaurant_id
    ),
    'dailyRevenue', (
      select coalesce(jsonb_agg(
        jsonb_build_object(
          'label', to_char(day_series.day_value, 'Dy'),
          'date', day_series.day_value,
          'revenue', coalesce(day_totals.revenue, 0),
          'orders', coalesce(day_totals.orders, 0)
        ) order by day_series.day_value
      ), '[]'::jsonb)
      from (
        select generate_series(current_date - interval '6 days', current_date, interval '1 day')::date as day_value
      ) day_series
      left join (
        select date(created_at) as order_day, count(*) as orders,
               sum(total_price) filter (where is_verified = true) as revenue
        from public.orders
        where restaurant_id = session_row.restaurant_id
          and created_at >= current_date - interval '6 days'
        group by date(created_at)
      ) day_totals on day_totals.order_day = day_series.day_value
    ),
    'hourly', (
      select coalesce(jsonb_agg(
        jsonb_build_object('hour', h.hour, 'orders', coalesce(hc.orders, 0), 'revenue', coalesce(hc.revenue, 0))
        order by h.hour
      ), '[]'::jsonb)
      from generate_series(0, 23) as h(hour)
      left join (
        select extract(hour from created_at)::int as hour, count(*) as orders,
               sum(total_price) filter (where is_verified = true) as revenue
        from public.orders
        where restaurant_id = session_row.restaurant_id
          and created_at between range_from and range_to
        group by 1
      ) hc on hc.hour = h.hour
    ),
    'categoryBreakdown', (
      select coalesce(jsonb_agg(
        jsonb_build_object('category', cat.category, 'quantity', cat.quantity, 'revenue', cat.revenue)
        order by cat.revenue desc
      ), '[]'::jsonb)
      from (
        select mi.category, sum(oi.quantity) as quantity, sum(oi.quantity * oi.price_at_time) as revenue
        from public.order_items oi
        join public.orders o on o.id = oi.order_id
        join public.menu_items mi on mi.id = oi.menu_item_id
        where o.restaurant_id = session_row.restaurant_id
          and o.created_at between range_from and range_to
        group by mi.category
      ) cat
    ),
    'statusFunnel', (
      select coalesce(jsonb_object_agg(status, cnt), '{}'::jsonb)
      from (
        select status, count(*) as cnt
        from public.orders
        where restaurant_id = session_row.restaurant_id
          and created_at between range_from and range_to
        group by status
      ) sf
    ),
    'topItems', (
      select coalesce(jsonb_agg(
        jsonb_build_object('name', item_stats.name, 'quantity', item_stats.quantity, 'revenue', item_stats.revenue)
        order by item_stats.quantity desc, item_stats.revenue desc
      ), '[]'::jsonb)
      from (
        select mi.name, sum(oi.quantity) as quantity, sum(oi.quantity * oi.price_at_time) as revenue
        from public.order_items oi
        join public.orders o on o.id = oi.order_id
        join public.menu_items mi on mi.id = oi.menu_item_id
        where o.restaurant_id = session_row.restaurant_id
          and o.created_at between range_from and range_to
        group by mi.name
        order by quantity desc, revenue desc
        limit 8
      ) item_stats
    )
  );
end;
$$;

