          'servedAt', o.served_at,
          'expiresAt', ov.expires_at,
          'items', coalesce(
            (
              select jsonb_agg(
                jsonb_build_object(
                  'menuItemId', mi.id,
                  'name', mi.name,
                  'quantity', oi.quantity,
