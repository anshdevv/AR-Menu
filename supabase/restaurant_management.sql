-- ---------------------------------------------------------------------------
-- Helper: expire stale pending orders
-- ---------------------------------------------------------------------------
create or replace function public.expire_pending_orders()
returns integer
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  updated_count integer := 0;
begin
  update public.orders
  set status = 'expired',
      is_verified = false
  where status = 'pending_verification'
    and exists (
      select 1
      from public.order_verifications ov
      where ov.order_id = public.orders.id
        and ov.verified_at is null
        and ov.expires_at <= now()
    );

  get diagnostics updated_count = row_count;
  return updated_count;
end;
$$;

-- ---------------------------------------------------------------------------
-- Helper: validate an admin session token, return the admin context
-- ---------------------------------------------------------------------------
create or replace function public._require_admin_session(p_session_token text)
returns table (
  admin_id bigint,
  restaurant_id bigint,
  email varchar,
  role varchar
)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  normalized_token text := trim(coalesce(p_session_token, ''));
  hashed_token text;
begin
  if normalized_token = '' then
    raise exception 'Please sign in to continue.';
  end if;

  hashed_token := encode(digest(normalized_token, 'sha256'), 'hex');

  return query
  with matched_session as (
    select s.admin_id
    from public.admin_sessions s
    where s.token_hash = hashed_token
      and s.expires_at > now()
  )
  select a.id, a.restaurant_id, a.email, a.role
  from matched_session ms
  join public.admins a
    on a.id = ms.admin_id
  where a.is_active = true;

  if not found then
    raise exception 'Your admin session has expired. Please sign in again.';
  end if;

  update public.admin_sessions
  set last_seen_at = now()
  where token_hash = hashed_token;
end;
$$;

-- ---------------------------------------------------------------------------
-- Customer: resolve a table from its QR token
-- ---------------------------------------------------------------------------
create or replace function public.resolve_table(p_qr_token uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  result jsonb;
begin
  select jsonb_build_object(
    'tableId', t.id,
    'tableNumber', t.table_number,
    'restaurantId', t.restaurant_id,
    'restaurant', jsonb_build_object(
      'id', r.id,
      'name', r.name,
      'description', r.description,
      'location', r.location,
      'sampleTable', r.sample_table
    )
  )
  into result
  from public.tables t
  join public.restaurants r on r.id = t.restaurant_id
  where t.qr_token = p_qr_token
    and t.is_active = true;

  if result is null then
    raise exception 'Table not found or inactive.';
  end if;

  return result;
end;
$$;

-- ---------------------------------------------------------------------------
-- Customer: create an order (now table-aware)
-- ---------------------------------------------------------------------------
create or replace function public.create_order(
  p_restaurant_id bigint,
  p_table_id bigint default null,
  p_table_number text default null,
  p_customer_name text default null,
  p_special_request text default null,
  p_items jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  new_order_id bigint;
  verification_code varchar(6);
  verification_expires_at timestamptz := now() + interval '10 minutes';
  requested_count integer := 0;
  matched_count integer := 0;
  computed_total numeric(10, 2) := 0;
  resolved_table_number text := nullif(trim(coalesce(p_table_number, '')), '');
begin
  perform public.expire_pending_orders();

  if not exists (select 1 from public.restaurants where id = p_restaurant_id) then
    raise exception 'Restaurant not found.';
  end if;

  -- Resolve table number from table_id when provided.
  if p_table_id is not null then
    select t.table_number into resolved_table_number
    from public.tables t
    where t.id = p_table_id and t.restaurant_id = p_restaurant_id;
  end if;

  select count(*) into requested_count from jsonb_array_elements(p_items);
  if requested_count = 0 then
    raise exception 'Add at least one dish before placing an order.';
  end if;

  with requested_items as (
    select
      (item ->> 'menuItemId')::bigint as menu_item_id,
      greatest(1, coalesce((item ->> 'quantity')::integer, 0)) as quantity
    from jsonb_array_elements(p_items) item
  )
  select count(*), coalesce(sum(mi.price * ri.quantity), 0)
  into matched_count, computed_total
  from requested_items ri
  join public.menu_items mi
    on mi.id = ri.menu_item_id
   and mi.restaurant_id = p_restaurant_id
   and mi.is_available = true;

  if matched_count <> requested_count then
    raise exception 'One or more selected dishes are not available.';
  end if;

  loop
    verification_code := lpad((floor(random() * 900000) + 100000)::int::text, 6, '0');
    exit when not exists (
      select 1 from public.order_verifications where code = verification_code
    );
  end loop;

  insert into public.orders (
    restaurant_id, table_id, customer_name, table_number,
    special_request, status, total_price, is_verified
  )
  values (
    p_restaurant_id,
    p_table_id,
    nullif(trim(coalesce(p_customer_name, '')), ''),
    resolved_table_number,
    nullif(trim(coalesce(p_special_request, '')), ''),
    'pending_verification',
    computed_total,
    false
  )
  returning id into new_order_id;

  with requested_items as (
    select
      (item ->> 'menuItemId')::bigint as menu_item_id,
      greatest(1, coalesce((item ->> 'quantity')::integer, 0)) as quantity
    from jsonb_array_elements(p_items) item
  )
  insert into public.order_items (order_id, menu_item_id, quantity, price_at_time)
  select new_order_id, mi.id, ri.quantity, mi.price
  from requested_items ri
  join public.menu_items mi
    on mi.id = ri.menu_item_id
   and mi.restaurant_id = p_restaurant_id
   and mi.is_available = true;

  insert into public.order_verifications (order_id, code, expires_at)
  values (new_order_id, verification_code, verification_expires_at);

  return jsonb_build_object(
    'orderId', new_order_id,
    'verificationCode', verification_code,
    'expiresAt', verification_expires_at,
    'status', 'pending_verification',
    'totalPrice', computed_total
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- Customer: poll order status (now exposes lifecycle timestamps)
-- ---------------------------------------------------------------------------
create or replace function public.get_order_status(p_order_id bigint, p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  normalized_code text := trim(coalesce(p_code, ''));
  order_payload jsonb;
begin
  perform public.expire_pending_orders();

  select jsonb_build_object(
    'orderId', o.id,
    'restaurantId', o.restaurant_id,
    'customerName', o.customer_name,
    'tableNumber', o.table_number,
    'specialRequest', o.special_request,
    'status', o.status,
    'isVerified', o.is_verified,
    'totalPrice', o.total_price,
    'createdAt', o.created_at,
    'confirmedAt', o.confirmed_at,
    'prepStartedAt', o.prep_started_at,
    'readyAt', o.ready_at,
    'servedAt', o.served_at,
    'expiresAt', ov.expires_at,
    'verifiedAt', ov.verified_at,
    'items', coalesce(
      (
        select jsonb_agg(
          jsonb_build_object(
            'menuItemId', mi.id,
            'name', mi.name,
            'quantity', oi.quantity,
            'priceAtTime', oi.price_at_time,
            'lineTotal', oi.quantity * oi.price_at_time
          ) order by mi.name
        )
        from public.order_items oi
        join public.menu_items mi on mi.id = oi.menu_item_id
        where oi.order_id = o.id
      ),
      '[]'::jsonb
    )
  )
  into order_payload
  from public.orders o
  join public.order_verifications ov on ov.order_id = o.id
  where o.id = p_order_id and ov.code = normalized_code;

  if order_payload is null then
    raise exception 'Order not found.';
  end if;

  return order_payload;
end;
$$;

-- ---------------------------------------------------------------------------
-- Admin auth
-- ---------------------------------------------------------------------------
create or replace function public.admin_sign_in(p_email text, p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  matched_admin record;
  raw_session_token text;
  hashed_token text;
begin
  select a.id, a.restaurant_id, a.email, a.role, r.name as restaurant_name
  into matched_admin
  from public.admins a
  join public.restaurants r on r.id = a.restaurant_id
  where lower(a.email) = lower(trim(coalesce(p_email, '')))
    and a.is_active = true
    and a.password_hash = crypt(coalesce(p_password, ''), a.password_hash);

  if matched_admin is null then
    raise exception 'Incorrect email or password.';
  end if;

  raw_session_token := gen_random_uuid()::text || gen_random_uuid()::text;
  hashed_token := encode(digest(raw_session_token, 'sha256'), 'hex');

  insert into public.admin_sessions (admin_id, token_hash, expires_at)
  values (matched_admin.id, hashed_token, now() + interval '7 days');

  return jsonb_build_object(
    'sessionToken', raw_session_token,
    'admin', jsonb_build_object(
      'id', matched_admin.id,
      'email', matched_admin.email,
      'role', matched_admin.role,
      'restaurantId', matched_admin.restaurant_id,
      'restaurantName', matched_admin.restaurant_name
    )
  );
end;
$$;

create or replace function public.admin_sign_out(p_session_token text)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  hashed_token text := encode(digest(trim(coalesce(p_session_token, '')), 'sha256'), 'hex');
begin
  delete from public.admin_sessions where token_hash = hashed_token;
  return true;
end;
$$;

